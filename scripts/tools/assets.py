#!/usr/bin/env python3
"""Asset request loop. Agents ask, the human downloads, the next agent imports.
  python3 scripts/tools/assets.py list [status]        show requests (status: requested|received|all; default requested)
  python3 scripts/tools/assets.py add "title" --kind material|model|hdri|audio|font|character|texture --need "what exactly" --why "where it is used"
         [--used-by S-01,foyer] [--priority 1-3] [--search "terms"] [--target assets/models/furniture/] [--accept "2K PBR, glb"]
         (agents: add a request instead of inventing an asset; keep a code-built fallback and mark it # PLACEHOLDER)
  python3 scripts/tools/assets.py checklist            regenerate docs/ASSET_REQUESTS.md (the human's download checklist)
  python3 scripts/tools/assets.py import               file everything in assets/_inbox/ (names start with AR-nnn), record licenses
  python3 scripts/tools/assets.py verify               check received requests: files exist, license line present
Human: download -> rename to start with the request id (AR-007_oak_floor.zip) -> drop in assets/_inbox/ -> git add/commit/push. Optionally
put the author + page URL in AR-007.txt next to it (otherwise the request's own source list is recorded)."""
import json, sys, re, shutil, zipfile, hashlib, datetime, pathlib, argparse
ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "data/assets/requests.json"
INBOX = ROOT / "assets/_inbox"
LIC = ROOT / "assets/LICENSES.md"
DOC = ROOT / "docs/ASSET_REQUESTS.md"
SOURCES = {  # starting points, NOT exact pages: search the terms on the site and filter to the license shown
 "polyhaven": ("Poly Haven (CC0)", "https://polyhaven.com"), "ambientcg": ("ambientCG (CC0)", "https://ambientcg.com"),
 "quaternius": ("Quaternius (CC0)", "https://quaternius.com"), "kenney": ("Kenney (CC0)", "https://kenney.nl/assets"),
 "freesound": ("Freesound (filter: License = Creative Commons 0)", "https://freesound.org"), "gfonts": ("Google Fonts (OFL)", "https://fonts.google.com"),
 "sketchfab": ("Sketchfab (filter: CC0 / downloadable)", "https://sketchfab.com"), "makehuman": ("MakeHuman (CC0 output)", "https://www.makehumancommunity.org"),
}
DEFAULT_SOURCES = {"material": ["polyhaven", "ambientcg"], "texture": ["polyhaven", "ambientcg"], "hdri": ["polyhaven"], "model": ["polyhaven", "quaternius", "sketchfab"],
                   "audio": ["freesound"], "font": ["gfonts"], "character": ["makehuman", "sketchfab"]}

def load(): return json.loads(DATA.read_text(encoding="utf-8"))
def save(d): DATA.write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
def by_id(d, i): return next((r for r in d["requests"] if r["id"] == i), None)

def cmd_list(a):
    st = (a[0] if a else "requested"); d = load()
    for r in sorted(d["requests"], key=lambda r: (r["priority"], r["id"])):
        if st == "all" or r["status"] == st:
            print("%s  P%d  %-9s %-9s %s  -> %s" % (r["id"], r["priority"], r["kind"], r["status"], r["title"], r["target"]))

def cmd_add(argv):
    p = argparse.ArgumentParser(); p.add_argument("title"); p.add_argument("--kind", required=True); p.add_argument("--need", required=True); p.add_argument("--why", required=True)
    p.add_argument("--used-by", default=""); p.add_argument("--priority", type=int, default=2); p.add_argument("--search", default=""); p.add_argument("--target", default="")
    p.add_argument("--accept", default="CC0 or CC-BY, 2K max for textures, glb for models")
    x = p.parse_args(argv); d = load()
    n = max([int(r["id"][3:]) for r in d["requests"]] + [0]) + 1
    kind = x.kind; tgt = x.target or {"material": "assets/textures/", "texture": "assets/textures/", "hdri": "assets/textures/hdri/", "model": "assets/models/", "audio": "assets/audio/", "font": "assets/fonts/", "character": "assets/models/characters/"}.get(kind, "assets/")
    r = {"id": "AR-%03d" % n, "title": x.title, "kind": kind, "need": x.need, "why": x.why, "used_by": [s for s in x.used_by.split(",") if s], "priority": x.priority,
         "search": x.search or x.title, "sources": DEFAULT_SOURCES.get(kind, ["polyhaven"]), "accept": x.accept, "target": tgt, "status": "requested"}
    d["requests"].append(r); save(d); cmd_checklist(); print("added", r["id"])

def cmd_checklist(_=None):
    d = load(); out = ["# ASSET REQUESTS (generated by `python3 scripts/tools/assets.py checklist`; do not edit)", "",
        "**What this is:** things the agents need that they cannot download themselves. Each is free (CC0 preferred). Do the **Priority 1** ones first.",
        "**How:** open the site, search the terms, download the file, **rename it to start with the request id** (e.g. `AR-007_oak_floor.zip`), put it in `assets/_inbox/`, then `git add assets && git commit -m assets && git push`. An agent imports and records the license on its next session.",
        "Optional: `assets/_inbox/AR-007.txt` with the author and the page URL (otherwise the site's name is recorded). Links below are site starting points: search the given terms there; pick any good CC0 match.", ""]
    for pr, name in ((1, "Priority 1 (blocks the vertical slice / Act 1)"), (2, "Priority 2"), (3, "Priority 3 (nice to have)")):
        rs = [r for r in d["requests"] if r["priority"] == pr and r["status"] == "requested"]
        if not rs: continue
        out += ["## " + name, ""]
        for r in rs:
            links = ", ".join("[%s](%s)" % SOURCES[s] for s in r["sources"] if s in SOURCES)
            out += ["- [ ] **%s %s** (%s) -> `%s`" % (r["id"], r["title"], r["kind"], r["target"]),
                    "  - need: %s" % r["need"], "  - search: `%s` on %s" % (r["search"], links), "  - accept: %s; used by: %s" % (r["accept"], ", ".join(r["used_by"]) or "-")]
        out.append("")
    got = [r for r in d["requests"] if r["status"] == "received"]
    if got:
        out += ["## Received", ""] + ["- %s %s -> `%s`" % (r["id"], r["title"], r["target"]) for r in got] + [""]
    DOC.write_text("\n".join(out), encoding="utf-8")
    print("wrote", DOC.relative_to(ROOT), "(%d open)" % sum(1 for r in d["requests"] if r["status"] == "requested"))

def safe_extract(z, dest):
    for m in z.namelist():
        t = (dest / m).resolve()
        if not str(t).startswith(str(dest.resolve())): raise ValueError("unsafe path in zip: " + m)
    z.extractall(dest)

def cmd_import(_=None):
    d = load(); done = 0
    for f in sorted(INBOX.iterdir()):
        if f.is_dir() or f.suffix == ".txt" or f.name.startswith(".") or f.name == "README.md": continue
        m = re.match(r"(AR-\d{3})", f.name)
        if not m: print("skip (name must start with AR-nnn):", f.name); continue
        r = by_id(d, m[1])
        if r is None: print("skip (no such request):", f.name); continue
        dest = ROOT / r["target"]; dest.mkdir(parents=True, exist_ok=True) if r["target"].endswith("/") else dest.parent.mkdir(parents=True, exist_ok=True)
        files = []
        if f.suffix.lower() == ".zip":
            sub = dest / re.sub(r"^AR-\d{3}_?", "", f.stem) if r["target"].endswith("/") else dest
            sub.mkdir(parents=True, exist_ok=True)
            with zipfile.ZipFile(f) as z: safe_extract(z, sub); files = [str((sub / n).relative_to(ROOT)) for n in z.namelist() if not n.endswith("/")]
        else:
            tgt = (dest / re.sub(r"^AR-\d{3}_?", "", f.name)) if r["target"].endswith("/") else dest
            shutil.copy2(f, tgt); files = [str(tgt.relative_to(ROOT))]
        side = INBOX / (m[1] + ".txt"); note = side.read_text(encoding="utf-8").strip() if side.exists() else ""
        sha = hashlib.sha256(f.read_bytes()).hexdigest()[:12]
        src = ", ".join(SOURCES[s][1] for s in r["sources"] if s in SOURCES)
        license_match = re.search(r"(?im)^\\s*license\\s*:\\s*(.+)$", note)
        license_text = license_match.group(1).strip() if license_match else "UNVERIFIED - add License: CC0 (or exact approved license) to the sidecar"
        r["status"] = "received"; r["received"] = {"date": datetime.date.today().isoformat(), "files": files[:50], "file_count": len(files), "sha256_12": sha, "note": note or "(no note: see sources)"}
        if not LIC.exists(): LIC.write_text("# Asset licenses\nEvery external asset needs an explicit license and source URL. Unverified entries block validation.\n\n| request | title | files | source / note | license | used by |\n|---|---|---|---|---|---|\n", encoding="utf-8")
        with LIC.open("a", encoding="utf-8") as fh:
            fh.write("| %s | %s | %s | %s | %s | %s |\n" % (r["id"], r["title"], ", ".join(files), (note.replace("\n", " ") or src), license_text, ", ".join(r["used_by"])))
        (INBOX / "_done").mkdir(exist_ok=True); shutil.move(str(f), str(INBOX / "_done" / f.name))
        if side.exists(): shutil.move(str(side), str(INBOX / "_done" / side.name))
        print("imported", r["id"], "->", r["target"], "(%d files)" % len(files)); done += 1
    save(d); cmd_checklist(); print("done:", done)

def cmd_verify(_=None):
    d = load(); bad = 0; lic = LIC.read_text(encoding="utf-8") if LIC.exists() else ""
    for r in d["requests"]:
        if r["status"] != "received": continue
        for p in r["received"]["files"][:5]:
            if not (ROOT / p).exists(): print("MISSING", r["id"], p); bad += 1
        if r["id"] not in lic: print("NO LICENSE LINE", r["id"]); bad += 1
    print("verify:", "OK" if not bad else "%d problems" % bad); sys.exit(1 if bad else 0)

if __name__ == "__main__":
    c = sys.argv[1] if len(sys.argv) > 1 else ""
    {"list": cmd_list, "add": cmd_add, "checklist": cmd_checklist, "import": cmd_import, "verify": cmd_verify}.get(c, lambda *_: sys.exit(__doc__))(*([sys.argv[2:]] if c in ("list", "add") else []))
